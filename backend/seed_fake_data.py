# ── Dates: 4 preceding business days + today ─────────────────────────────
def last_n_business_days(n: int) -> list[datetime.date]:
    """Return n dates: the (n-1) business days before today, then today."""
    preceding = []
    d = datetime.date.today() - datetime.timedelta(days=1)
    while len(preceding) < n - 1:
        if d.weekday() < 5:   # Mon–Fri
            preceding.append(d)
        d -= datetime.timedelta(days=1)
    return list(reversed(preceding)) + [datetime.date.today()]

# ── Main seeding logic ────────────────────────────────────────────────────
def seed():
    db = SessionLocal()
    dates = last_n_business_days(5)
    print(f"Seeding holdings for dates: {[d.isoformat() for d in dates]}")

    # Ensure stock records exist
    stock_cache: dict[str, models.Stock] = {}
    for ticker, (name, sector) in STOCKS.items():
        s = db.query(models.Stock).filter(models.Stock.ticker == ticker).first()
        if not s:
            s = models.Stock(ticker=ticker, name=name, sector=sector)
            db.add(s)
        else:
            s.name = name
            s.sector = sector
        stock_cache[ticker] = s
    db.flush()

    # Ensure ETF records exist
    etf_cache: dict[str, models.ETF] = {}
    for e in db.query(models.ETF).all():
        etf_cache[e.ticker] = e

    # Wipe all existing holdings for these dates so seed is idempotent
    for d in dates:
        db.query(models.Holding).filter(models.Holding.date == d).delete()
    db.flush()

    # Insert holdings
    total = 0
    for etf_ticker, snapshots in HOLDINGS.items():
        etf = etf_cache.get(etf_ticker)
        if not etf:
            print(f"  ⚠ ETF {etf_ticker} not found in DB — skipping (run the server once to seed ETFs)")
            continue

        for idx, (date, snapshot) in enumerate(zip(dates, snapshots)):
            for (sticker, weight, shares) in snapshot:
                stock = stock_cache.get(sticker)
                if not stock:
                    print(f"  ⚠ Stock {sticker} not in STOCKS dict — skipping")
                    continue
                h = models.Holding(
                    etf_id=etf.id,
                    stock_id=stock.id,
                    weight=weight,
                    shares=float(shares),
                    date=date,
                )
                db.add(h)
                total += 1

        print(f"  {etf_ticker}: {sum(len(s) for s in snapshots)} holdings across {len(snapshots)} dates")

    db.commit()
    print(f"\n✓ Seeded {total} holding rows across {len(dates)} dates.")
    print("  Test the app at http://localhost:4200")

if __name__ == "__main__":
    seed()
